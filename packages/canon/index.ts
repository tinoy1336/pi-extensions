const HANDLE_LEN = 6;

type Audience = "all" | "parent" | "foreman" | "subagent";

/** Every audience value, in group-render order (also the label order). ONE list:
 *  the store validator, the scope-group rank and the tool validators all read it,
 *  so a new audience is added here and nowhere else. */
const AUDIENCE_ORDER: readonly Audience[] = [
	"all",
	"parent",
	"foreman",
	"subagent",
];

/** Is this string one of the audience values? */
function isAudience(value: string): value is Audience {
	return (AUDIENCE_ORDER as readonly string[]).includes(value);
}

/** One audience parameter, declared over the closed set: a union of literals reaches
 *  the model as a real enum, so a value outside it cannot be sent at all. The runtime
 *  validator stays where it is — the schema constrains the call, it does not prove
 *  anything about what arrives. */
function audienceSchema(description: string) {
	return Type.Union(
		AUDIENCE_ORDER.map((a) => Type.Literal(a)),
		{ description },
	);
}

