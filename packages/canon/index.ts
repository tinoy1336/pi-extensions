	const registration: CanonRegistration = {
		namespace: NAMESPACE,
		onEvent(event: {
			type: string;
			fromSessionId?: string;
			payload?: unknown;
		}): void {
			if (event.type !== "message" || typeof event.fromSessionId !== "string")
				return;
			if (mySessionId !== null && event.fromSessionId === mySessionId) return;
			const payload = event.payload as Partial<CanonNotice> | null;
			if (!payload || payload.type !== "canon" || !payload.scope || !payload.id)
				return;
			if (!matches(payload.scope, currentModel(), audiences)) {
				// Withholding is otherwise unattributable: nothing is delivered and nothing is
				// sent back, so a scope mismatch leaves no trace on either side. The decision is
				// unchanged here — only the record of it is added.
				hookLog("canon", "notice-withheld", {
					namespace: NAMESPACE,
					id: payload.id,
					op: payload.op,
					entryModel: payload.scope.model,
					entryAudience: payload.scope.audience,
					sessionModel: currentModel(),
					sessionAudience: sessionLabel(audiences),
					mismatch:
						payload.scope.audience !== "all" && !audiences.has(payload.scope.audience)
							? "audience"
							: "model",
				});
				return;
			}
			const sender = payload.sender?.trim() || event.fromSessionId.slice(0, 8);
			const verb =
				payload.op === "remove" || payload.op === "category_remove"
					? "removed"
					: payload.op === "edit" || payload.op === "category_edit"
						? "edited"
						: "added";
			pi.sendMessage(
				{
					customType: "canon_notice",
					content: `**Canon ${verb} (${payload.scope.model} / ${payload.scope.audience})**\n[${payload.id}] ${payload.text}${payload.detail ? `\n${payload.detail}` : ""}\n— from ${sender}`,
					display: true,
					details: { fromSessionId: event.fromSessionId, canonId: payload.id },
				},
				// An idle session takes the passive queue, because steer would wake it like a
				// prompt; a run already in flight takes steer, which lands at the next tool
				// boundary instead of waiting for a turn that has not started.
				{ deliverAs: runInFlight ? "steer" : "nextTurn" },
			);
		},
		onReady(readyChannel: CanonChannel): void {
			channel = readyChannel;
		},
	};

	function register() {
		pi.events.emit("intercom:extension-register", registration);
	}

