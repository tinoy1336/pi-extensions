/**
 * Canon Extension
 *
 * Tool-managed binding system-prompt lines (rules + learned facts), scoped by
 * model (global | <model-id>) and audience (all | parent | foreman | subagent).
 * An entry's audience is a MEMBERSHIP test against the audience set its session
 * belongs to, not a single session kind: a foreman session is {parent, foreman}.
 * Injected into every matching session's system prompt at session start via
 * before_agent_start AND guaranteed on every provider request by the
 * normalization in before_provider_request (see the block comment there). The
 * injected block is a session-start snapshot — the system prompt is
 * prompt-cache-frozen, so runtime edits NEVER change a running session's
 * block; new sessions get the current full list, running sessions learn of
 * changes via canon notices (and the user's /canon list).
 * Edited at runtime via canon_add / canon_remove / canon_edit (plus
 * the /canon command). Changes are broadcast to peer sessions
 * over the `ipc` transport's extension bus (namespace "canon"); each receiver matches
 * the entry scope against its own model + audience before showing a notice.
 *
 * Replaces APPEND_SYSTEM.md (global/parent) and FLASH.md (global/subagent).
 * Audience detection is one per-process set, read once at load (sessionAudiences).
 * A child session is recognised by EITHER of two markers, because there are two
 * launch paths: PI_SUBAGENT=1, exported by ~/.local/bin/pi-subagent and inherited
 * by the pi processes it starts, and PI_SUBAGENT_CHILD=1, set in process.env by
 * the pi-subagents async runner at module load, before the child session it hosts
 * loads any extension. Either marker means {subagent}; otherwise {parent}, plus
 * {foreman} when PI_FOREMAN=1, the value the pi-foreman launcher exports for the
 * session it execs. The environment is the only signal present before the block
 * renders, and it cannot change within a session, so the block is fixed for that
 * session's life.
 *
 * Store: ~/.pi/agent/canon/canon.json — { entries: [{id, text, model, audience, category?}], categories: [{id, title}] }
 * Categories are un-ordered; entries reference them by id. They render as sub-headings
 * inside scope groups (store insertion order), with uncategorized entries last, and
 * each heading carries the store's own id after the word `category`
 * (`#### Behavioural Preferences [category 1cg5lr]`) — the word keeps the category id
 * from reading as an entry handle, which the block renders as `[1i15c2]`.
 * canon_add REQUIRES a category and canon_edit can only CHANGE one: every refusal
 * lists the valid ids with their titles, so a retry costs no lookup call. The store
 * validator counts entries that are uncategorized or
 * carry a category id the store no longer holds (both render as Uncategorized) and
 * reports the count to the hook log once per distinct state.
 * The injected block and the /canon list output are ONE rendering, grouping entries
 * under scope headers (model × audience) — scope is NEVER repeated per line, and the
 * listing adds nothing the block does not carry, so it shows a session its own block.
 * Lines keep their [id] handle (the
 * model needs it for canon_remove/canon_edit and to correlate notices and the listing).
 * Handles: opaque 6-char base36 ids generated by this extension, never reused.
 */
