	/** What the /canon argument accepts at each position, filtered by what has been
	 *  typed. Before the first space the argument is the verb; after `list` it is the
	 *  scope, and the value inserted is the whole argument rather than the scope alone. */
	function canonCompletions(
		argumentPrefix: string,
	): Array<{ value: string; label: string; description: string }> | null {
		// The trailing space is KEPT: it is what separates the verb from the scope, and
		// trimming the whole argument would put `list ` back in the verb branch.
		const typed = argumentPrefix ?? "";
		const space = typed.indexOf(" ");
		if (space === -1) {
			const typedVerb = typed.trim().toLowerCase();
			const items = VERBS.filter((v) => v.startsWith(typedVerb)).map((v) => ({
				value: v,
				label: v,
				description: VERB_DESCRIPTIONS[v],
			}));
			return items.length > 0 ? items : null;
		}
		const verb = typed.slice(0, space).trim().toLowerCase();
		if (verb !== "list") return null;
		const scopePrefix = typed.slice(space + 1).trim().toLowerCase();
		const items = scopeValues(loadStore())
			.filter((v) => v.value.toLowerCase().startsWith(scopePrefix))
			.map((v) => ({
				value: `${verb} ${v.value}`,
				label: v.value,
				description: v.description,
			}));
		return items.length > 0 ? items : null;
	}

	pi.registerCommand("canon", {
		description:
			"Manage canon lines: list [scope] | add [--model M] [--audience A] <text> | remove <id> | edit <id> <text> | category list|add|edit|remove. `list` prints the block this session receives; a scope argument (an audience word or a model id) prints the block that scope receives instead. Tab completes the verbs and the scope values.",
		getArgumentCompletions: canonCompletions,
		handler: async (args, ctx) => {
			const tokens = (args ?? "").trim().split(/\s+/).filter(Boolean);
			const verb = tokens[0] ?? "list";
			try {
				if (verb === "list") {
					const store = loadStore();
					const scope = tokens[1]?.toLowerCase();
					const values = scopeValues(store);
					// A scope neither the completion list nor the store offers is a typo, not an
					// empty session: name the values that exist instead of printing nothing. The
					// resolved form counts too, because the model branch strips a provider prefix.
					const known = (name: string): boolean =>
						values.some((v) => v.value.toLowerCase() === name);
					if (
						scope &&
						!isAudience(scope) &&
						!known(scope) &&
						!known(normalizeModel(scope))
					) {
						ctx.ui.notify(
							`Unknown scope "${scope}". Valid scopes: ${values.map((v) => v.value).join(", ")}. No scope prints this session's block.`,
							"error",
						);
						return;
					}
					// ONE rendering, the same one the injected block uses: same headings, same
					// grouping and order, same lines, and nothing else — no counts, no scope echo,
					// no reasons, no descriptions, no empty sections. A scope argument renders the
					// block THAT scope receives instead: an audience word for another audience set,
					// a model id for another active model.
					const model =
						scope && !isAudience(scope) ? normalizeModel(scope) : currentModel();
					const scopeAudiences =
						scope && isAudience(scope) ? new Set<Audience>([scope]) : audiences;
					ctx.ui.notify(render(store, model, scopeAudiences), "info");
					return;
				}
				const store = loadStore();
				if (verb === "category") {
					const sub = tokens[1];
					if (sub === "list") {
						ctx.ui.notify(
							store.categories.length
								? store.categories
										.map((c) => `[${c.id}] ${c.title}`)
										.join("\n")
								: "(no categories)",
							"info",
						);
						return;
					}
					if (sub === "add") {
						const title = tokens.slice(2).join(" ").trim();
						if (!title) {
							ctx.ui.notify("Usage: /canon category add <title>", "error");
							return;
						}
						const id = genId(store);
						store.categories.push({ id, title });
						saveStore(store);
						publishNotice({
							op: "category_add",
							scope: { model: "global", audience: "all" },
							id,
							text: title,
						});
						ctx.ui.notify(`Added category [${id}] ${title}`, "info");
						return;
					}
					if (sub === "edit") {
						const id = tokens[2];
						const cat = store.categories.find((c) => c.id === id);
						if (!cat) {
							ctx.ui.notify(`No category with id "${id ?? ""}"`, "error");
							return;
						}
						const newTitle = tokens.slice(3).join(" ").trim();
						if (newTitle) cat.title = newTitle;
						saveStore(store);
						publishNotice({
							op: "category_edit",
							scope: { model: "global", audience: "all" },
							id: cat.id,
							text: cat.title,
						});
						ctx.ui.notify(`Edited category [${cat.id}] ${cat.title}`, "info");
						return;
					}
					if (sub === "remove" || sub === "rm") {
						const id = tokens[2];
						const idx = store.categories.findIndex((c) => c.id === id);
						if (!id || idx === -1) {
							ctx.ui.notify(`No category with id "${id ?? ""}"`, "error");
							return;
						}
						const [removed] = store.categories.splice(idx, 1);
						let detached = 0;
						for (const e of store.entries) {
							if (e.category === removed.id) {
								delete e.category;
								detached++;
							}
						}
						saveStore(store);
						publishNotice({
							op: "category_remove",
							scope: { model: "global", audience: "all" },
							id: removed.id,
							text: removed.title,
							...(detached
								? { detail: `${detached} entries detached to Uncategorized` }
								: {}),
						});
						ctx.ui.notify(
							`Removed category [${removed.id}]${detached ? ` (${detached} detached)` : ""}`,
							"info",
						);
						return;
					}
					ctx.ui.notify(
						"Usage: /canon category list | add <title> | edit <id> [<title>] | remove <id>",
						"error",
					);
					return;
				}
				if (verb === "add") {
					let model = "global";
					let audience: Audience = "all";
					const rest: string[] = [];
					for (let i = 1; i < tokens.length; i++) {
						if (tokens[i] === "--model" && tokens[i + 1])
							model = normalizeModel(tokens[++i]);
						else if (tokens[i] === "--audience" && tokens[i + 1]) {
							const a = tokens[++i];
							if (isAudience(a)) audience = a;
							else {
								ctx.ui.notify(
									`Invalid audience "${a}": use one of ${AUDIENCE_ORDER.join(", ")}`,
									"error",
								);
								return;
							}
						} else rest.push(tokens[i]);
					}
					const text = rest.join(" ");
					if (!text) {
						ctx.ui.notify("Usage: /canon add [--model M] [--audience A] <text>", "error");
						return;
					}
					const id = genId(store);
					store.entries.push({ id, text, model, audience });
					saveStore(store);
					publishNotice({
						op: "add",
						scope: { model, audience },
						id,
						text,
					});
					ctx.ui.notify(`Added canon [${id}] (${model} / ${audience})`, "info");
					return;
				}
				if (verb === "remove" || verb === "rm") {
					const id = tokens[1];
					const idx = store.entries.findIndex((e) => e.id === id);
					if (!id || idx === -1) {
						ctx.ui.notify(`No canon line with id "${id ?? ""}"`, "error");
						return;
					}
					const [removed] = store.entries.splice(idx, 1);
					saveStore(store);
					publishNotice({
						op: "remove",
						scope: { model: removed.model, audience: removed.audience },
						id: removed.id,
						text: removed.text,
					});
					ctx.ui.notify(`Removed canon [${removed.id}]`, "info");
					return;
				}
				if (verb === "edit") {
					const id = tokens[1];
					const text = tokens.slice(2).join(" ");
					const entry = store.entries.find((e) => e.id === id);
					if (!id || !entry || !text) {
						ctx.ui.notify("Usage: /canon edit <id> <new text>", "error");
						return;
					}
					entry.text = text;
					saveStore(store);
					publishNotice({
						op: "edit",
						scope: { model: entry.model, audience: entry.audience },
						id: entry.id,
						text,
					});
					ctx.ui.notify(`Edited canon [${entry.id}]`, "info");
					return;
				}
				ctx.ui.notify(
					"Usage: /canon list [scope] | add [--model M] [--audience A] <text> | remove <id> | edit <id> <new text>",
					"error",
				);
			} catch (err) {
				ctx.ui.notify(
					`canon: ${err instanceof Error ? err.message : String(err)}`,
					"error",
				);
			}
		},
	});
