	// Guard, not repair: a payload whose system prompt has a shape we cannot
	// rewrite would silently keep the path-dependent asymmetry. One line per
	// process is enough to make that visible; the request itself is untouched.
	let unrepairableLogged = false;
	/** Suppresses repeats of the expected wake-path repair line: a wake run's
	 *  every request arrives base-only and is normalized, but one line names the
	 *  run. An anomaly (fired === true) is never suppressed. */
	let wakeRepairLogged = false;
	pi.on("before_provider_request", (event) => {
		try {
			if (unrepairableLogged) return undefined;
			const payload = (event as { payload?: unknown })?.payload as
				| Record<string, unknown>
				| undefined;
			if (!payload || typeof payload !== "object") return undefined;
			if (systemPromptSlot(payload)) return undefined;
			unrepairableLogged = true;
			hookLog("canon", "prompt-unrepairable", {
				keys: Object.keys(payload).slice(0, 24),
			});
		} catch {
			/* diagnostics must never break a provider request */
		}
		return undefined;
	});

	// Best-effort peer notice: the store write has already landed when this runs,
	// so EVERY failure mode of the channel call is swallowed here and logged:
	//   - the channel's publish may throw SYNCHRONOUSLY when the transport is
	//     down, and returns void, so there is no promise to catch;
	//   - it returns void, so .catch must only ever be reached through the
	//     optional call (chaining it directly was the TypeError that escaped);
	//   - a promise-returning build rejects instead of throwing — the guarded
	//     handler logs that too, so it can not become an unhandled rejection.
	// A lost notice is NOT surfaced in the tool result: the result reports the
	// STORE outcome (see the call sites), while the notice is ancillary — a
	// failed announcement must never turn a successful edit into a failure.
	function publishNotice(notice: Omit<CanonNotice, "type" | "sender">): void {
		if (!channel) return;
		try {
			const payload: CanonNotice = {
				...notice,
				type: "canon",
				sender: pi.getSessionName() || undefined,
			};
			const result = channel.publish(payload, { audience: "capable" });
			result?.catch?.(() => {
				hookLog("canon", "notice-failed", {
					op: notice.op,
					id: notice.id,
					reason: "publish rejected",
				});
			});
		} catch (err) {
			hookLog("canon", "notice-failed", {
				op: notice.op,
				id: notice.id,
				reason: err instanceof Error ? err.message : String(err),
			});
		}
	}

